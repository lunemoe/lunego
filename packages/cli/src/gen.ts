import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { basename, join, relative } from 'node:path'
import { generateAssets } from './assets.js'
import { scanContent } from './content-scan.js'
import {
  featureDirs,
  pathExists,
  readSchemaLock,
  readSchemaVersion,
  schemaDigest,
  toPosix,
  walkFiles,
  writeSchemaLock,
} from './project.js'

export interface GenResult {
  readonly errors: readonly string[]
  readonly files: readonly string[]
}

function compareText(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0
}

async function moduleFiles(dir: string): Promise<string[]> {
  try {
    const entries = await readdir(dir, { withFileTypes: true })
    return entries
      .filter((entry) => entry.isFile() && entry.name.endsWith('.ts') && !entry.name.endsWith('.test.ts'))
      .map((entry) => join(dir, entry.name))
      .sort(compareText)
  } catch {
    return []
  }
}

function registrySource(featureDir: string, systems: readonly string[], handlers: readonly string[]): string {
  const lines = ['// Generated by lunego gen. Do not edit (LG014).', '']
  systems.forEach((file, index) => {
    const relativePath = toPosix(relative(join(featureDir, '_generated'), file)).replace(/\.ts$/, '.js')
    lines.push(`import system${index} from '${relativePath}'`)
  })
  handlers.forEach((file, index) => {
    const relativePath = toPosix(relative(join(featureDir, '_generated'), file)).replace(/\.ts$/, '.js')
    lines.push(`import handler${index} from '${relativePath}'`)
  })
  if (lines.length > 2) {
    lines.push('')
  }
  lines.push(`export const systems = [${systems.map((_, index) => `system${index}`).join(', ')}] as const`)
  lines.push(
    `export const handlers = [${handlers.map((_, index) => `handler${index}`).join(', ')}] as const`,
  )
  lines.push('')
  return lines.join('\n')
}

function collectIds(text: string, pattern: RegExp): string[] {
  const ids = new Set<string>()
  for (const match of text.matchAll(pattern)) {
    ids.add(match[1])
  }
  return [...ids].sort(compareText)
}

function objectLiteral(entries: ReadonlyArray<readonly [string, string]>, indent: string): string {
  const body = entries
    .map(([key, value]) => `${indent}${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n')
  return `{\n${body}\n}`
}

function idsSource(
  cueIds: readonly string[],
  contentTypes: readonly string[],
  content: ReadonlyMap<string, ReadonlySet<string>>,
): string {
  const hasContent = content.size > 0
  const cueLiteral = objectLiteral(
    cueIds.map((id) => [id, id] as const),
    '  ',
  )
  const typeLiteral = objectLiteral(
    contentTypes.map((id) => [id, id] as const),
    '  ',
  )
  const contentLines = [...content.keys()].sort(compareText).map((type) => {
    const ids = [...(content.get(type) ?? [])].sort(compareText)
    const entries = ids
      .map((id) => `      ${JSON.stringify(id)}: ${JSON.stringify(id)} as ContentId<${JSON.stringify(type)}>,`)
      .join('\n')
    return `  ${JSON.stringify(type)}: {\n${entries}\n  },`
  })
  return [
    '// Generated by lunego gen. Do not edit (LG014).',
    ...(hasContent ? ["import type { ContentId } from '@lunego/core'", ''] : []),
    `export const CueIds = ${cueLiteral} as const`,
    'export type CueId = (typeof CueIds)[keyof typeof CueIds]',
    '',
    `export const ContentTypeIds = ${typeLiteral} as const`,
    'export type ContentTypeId = (typeof ContentTypeIds)[keyof typeof ContentTypeIds]',
    '',
    'export const ContentIds = {',
    ...contentLines,
    '} as const',
    '',
  ].join('\n')
}

async function collectIdSources(cwd: string): Promise<string> {
  const files = await walkFiles(join(cwd, 'features'), ['_generated'])
  const cueIds = new Set<string>()
  for (const file of files.filter((candidate) => candidate.endsWith('.ts'))) {
    const text = await readFile(file, 'utf8')
    for (const id of collectIds(text, /defineCue\(\s*['"]([^'"]+)['"]/g)) {
      cueIds.add(id)
    }
  }
  const scanned = await scanContent(cwd)
  return idsSource(
    [...cueIds].sort(compareText),
    [...scanned.types].sort(compareText),
    scanned.content,
  )
}

async function ensureLock(cwd: string, check: boolean, errors: string[]): Promise<void> {
  const version = await readSchemaVersion(cwd)
  const digest = await schemaDigest(cwd)
  const lock = await readSchemaLock(cwd)
  if (check) {
    if (lock !== null && (lock.schemaVersion !== version || lock.digest !== digest)) {
      errors.push(
        `LG010 schema.lock.json is stale (version ${lock.schemaVersion} vs ${version}); bump schemaVersion and run lunego gen`,
      )
    }
    return
  }
  if (lock === null || lock.schemaVersion !== version) {
    await writeSchemaLock(cwd, { schemaVersion: version, digest })
  }
}

export async function generate(cwd: string, check: boolean): Promise<GenResult> {
  const errors: string[] = []
  const files: string[] = []
  const expected = new Map<string, string>()
  const features = await featureDirs(cwd)
  for (const featureDir of features) {
    const name = basename(featureDir)
    const systems = await moduleFiles(join(featureDir, 'logic', 'systems'))
    const handlers = await moduleFiles(join(featureDir, 'logic', 'handlers'))
    const path = join(featureDir, '_generated', 'registry.ts')
    expected.set(path, registrySource(featureDir, systems, handlers))
    files.push(toPosix(relative(cwd, path)))
    void name
  }
  const idsPath = join(cwd, 'features', '_generated', 'ids.ts')
  expected.set(idsPath, await collectIdSources(cwd))
  files.push(toPosix(relative(cwd, idsPath)))
  const assets = await generateAssets(cwd)
  if (assets !== null) {
    errors.push(...assets.errors)
    if (assets.errors.length === 0) {
      expected.set(assets.path, assets.source)
      files.push(toPosix(relative(cwd, assets.path)))
    }
  }

  for (const [path, content] of expected) {
    const exists = await pathExists(path)
    const current = exists ? await readFile(path, 'utf8') : null
    if (check) {
      if (current !== content) {
        errors.push(`LG014 ${toPosix(relative(cwd, path))} is stale; run lunego gen`)
      }
    } else if (current !== content) {
      await mkdir(join(path, '..'), { recursive: true })
      await writeFile(path, content, 'utf8')
    }
  }
  await ensureLock(cwd, check, errors)
  return { errors, files }
}
