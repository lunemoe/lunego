import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import { compareText, stableStringify, type AssetEntry, type AssetManifest } from './assets-schema.js'
import { readAssetManifest } from './assets-manifest.js'
import { validateManifest } from './assets-validate.js'
import { pathExists, toPosix } from './project.js'

export interface AssetGeneration {
  readonly path: string
  readonly source: string
  readonly errors: readonly string[]
}

const METADATA_KEYS = [
  'file',
  'type',
  'frameWidth',
  'frameHeight',
  'columns',
  'rows',
  'frames',
  'margin',
  'spacing',
  'fps',
  'anchor',
  'animations',
  'nineSlice',
] as const

function metadata(entry: AssetEntry): Record<string, unknown> {
  const result: Record<string, unknown> = {
    file: entry.file,
    type: entry.type,
  }
  for (const key of METADATA_KEYS) {
    if (entry[key] !== undefined) {
      result[key] = entry[key]
    }
  }
  return result
}

function assetSource(
  pack: string,
  version: string | number,
  hash: string,
  entries: readonly AssetEntry[],
): string {
  const ids = entries.map((entry) => entry.id).sort(compareText)
  const assets = Object.fromEntries(
    [...entries]
      .sort((left, right) => compareText(left.id, right.id))
      .map((entry) => [entry.id, metadata(entry)]),
  )
  return [
    '// Generated by lunego gen. Do not edit (LG014).',
    '',
    `export const AssetPack = ${JSON.stringify({ pack, version, hash })} as const`,
    'export type AssetPackId = typeof AssetPack.pack',
    '',
    `export const AssetIds = ${JSON.stringify(
      Object.fromEntries(ids.map((id) => [id, id])),
      null,
      2,
    )} as const`,
    'export type AssetId = (typeof AssetIds)[keyof typeof AssetIds]',
    '',
    'export interface AssetFrameRect {',
    '  readonly x: number',
    '  readonly y: number',
    '  readonly width: number',
    '  readonly height: number',
    '}',
    '',
    'export interface AssetAnchorPoint {',
    '  readonly x: number',
    '  readonly y: number',
    '}',
    '',
    'export type AssetAnchor = string | AssetAnchorPoint',
    '',
    'export interface AssetAnimation {',
    '  readonly name: string',
    '  readonly columns?: readonly number[]',
    '  readonly frames?: number',
    '  readonly from?: number',
    '  readonly fps?: number | null',
    '  readonly loop?: boolean',
    '  readonly durations?: readonly number[]',
    '}',
    '',
    'export interface AssetDisplay {',
    '  readonly file: string',
    '  readonly type: string',
    '  readonly frameWidth?: number',
    '  readonly frameHeight?: number',
    '  readonly columns?: number',
    '  readonly rows?: number',
    '  readonly frames?: number | readonly AssetFrameRect[]',
    '  readonly margin?: number',
    '  readonly spacing?: number',
    '  readonly fps?: number | null',
    '  readonly anchor?: AssetAnchor',
    '  readonly animations?: readonly AssetAnimation[]',
    '  readonly nineSlice?: { readonly border: number; readonly cols?: number }',
    '}',
    '',
    `export const Assets = ${JSON.stringify(assets, null, 2)} as const satisfies Record<AssetId, AssetDisplay>`,
    '',
    'export function asset(id: AssetId): AssetDisplay {',
    '  return Assets[id]',
    '}',
    '',
  ].join('\n')
}

async function manifestHash(cwd: string, manifest: AssetManifest): Promise<string> {
  const hash = createHash('sha256')
  hash.update(stableStringify(manifest))
  for (const entry of [...manifest.assets].sort((left, right) => compareText(left.id, right.id))) {
    if (typeof entry.file !== 'string') {
      continue
    }
    const filePath = join(cwd, 'assets', entry.file)
    if (await pathExists(filePath)) {
      hash.update(toPosix(relative(cwd, filePath)))
      hash.update(await readFile(filePath))
    }
  }
  return hash.digest('hex')
}

export async function generateAssets(cwd: string): Promise<AssetGeneration | null> {
  const read = await readAssetManifest(cwd)
  if (read.manifest === undefined) {
    return read.errors.length === 0
      ? null
      : {
          path: join(cwd, 'features', '_generated', 'assets.ts'),
          source: '',
          errors: read.errors,
        }
  }
  const manifest = read.manifest
  const validation = await validateManifest(manifest, cwd)
  const path = join(cwd, 'features', '_generated', 'assets.ts')
  if (validation.errors.length > 0) {
    return { path, source: '', errors: validation.errors }
  }
  return {
    path,
    source: assetSource(
      manifest.pack,
      manifest.version,
      await manifestHash(cwd, manifest),
      manifest.assets,
    ),
    errors: [],
  }
}
