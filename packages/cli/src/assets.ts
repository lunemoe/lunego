import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import { pathExists, toPosix } from './project.js'

interface AssetAnimation {
  readonly name: string
  readonly columns: readonly number[]
  readonly frames: number
  readonly fps?: number | null
}

interface AssetEntry {
  readonly id: string
  readonly file: string
  readonly type: string
  readonly frameWidth?: number
  readonly frameHeight?: number
  readonly columns?: number
  readonly rows?: number
  readonly frames?: number
  readonly fps?: number | null
  readonly anchor?: string
  readonly animations?: readonly AssetAnimation[]
  readonly [key: string]: unknown
}

interface AssetManifest {
  readonly pack: string
  readonly version: string | number
  readonly assets: readonly AssetEntry[]
}

export interface AssetGeneration {
  readonly path: string
  readonly source: string
  readonly errors: readonly string[]
}

function positiveInteger(value: unknown, label: string, errors: string[]): boolean {
  if (typeof value !== 'number' || !Number.isInteger(value) || value <= 0) {
    errors.push(`LG009 ${label} must be a positive integer`)
    return false
  }
  return true
}

function validateEntry(entry: AssetEntry, index: number, errors: string[]): void {
  const label = `asset[${index}]`
  if (typeof entry.id !== 'string' || entry.id.length === 0) {
    errors.push(`LG009 ${label}.id must be a non-empty string`)
  }
  if (typeof entry.file !== 'string' || entry.file.length === 0) {
    errors.push(`LG009 ${label}.file must be a non-empty relative path`)
  } else if (entry.file.startsWith('/') || entry.file.split('/').includes('..')) {
    errors.push(`LG009 ${label}.file must stay inside assets/: ${entry.file}`)
  }
  if (typeof entry.type !== 'string' || entry.type.length === 0) {
    errors.push(`LG009 ${label}.type must be a non-empty string`)
  }
  for (const key of ['frameWidth', 'frameHeight', 'columns', 'rows', 'frames'] as const) {
    const value = entry[key]
    if (value !== undefined) {
      positiveInteger(value, `${label}.${key}`, errors)
    }
  }
  if (
    entry.frames !== undefined &&
    entry.columns !== undefined &&
    entry.rows !== undefined &&
    entry.frames > entry.columns * entry.rows
  ) {
    errors.push(`LG009 ${label}.frames ${entry.frames} exceeds ${entry.columns}x${entry.rows}`)
  }
  if (entry.fps !== undefined && entry.fps !== null) {
    if (typeof entry.fps !== 'number' || !Number.isFinite(entry.fps) || entry.fps <= 0) {
      errors.push(`LG009 ${label}.fps must be positive or null`)
    }
  }
  if (entry.animations !== undefined) {
    if (!Array.isArray(entry.animations)) {
      errors.push(`LG009 ${label}.animations must be an array`)
      return
    }
    const names = new Set<string>()
    for (const animation of entry.animations) {
      if (typeof animation.name !== 'string' || animation.name.length === 0) {
        errors.push(`LG009 ${label} animation name must be non-empty`)
        continue
      }
      if (names.has(animation.name)) {
        errors.push(`LG009 ${label} has duplicate animation ${animation.name}`)
      }
      names.add(animation.name)
      positiveInteger(animation.frames, `${label}.${animation.name}.frames`, errors)
      if (!Array.isArray(animation.columns) || !animation.columns.every((value: unknown) => typeof value === 'number' && Number.isInteger(value) && value >= 0)) {
        errors.push(`LG009 ${label}.${animation.name}.columns must be non-negative integers`)
      } else if (
        entry.columns !== undefined &&
        animation.columns.some((value: unknown) => typeof value === 'number' && value >= (entry.columns ?? 0))
      ) {
        errors.push(`LG009 ${label}.${animation.name}.columns exceed tileset columns`)
      }
    }
  }
}

function metadata(entry: AssetEntry): Record<string, unknown> {
  const result: Record<string, unknown> = {
    file: entry.file,
    type: entry.type,
  }
  for (const key of ['frameWidth', 'frameHeight', 'columns', 'rows', 'frames', 'fps', 'anchor', 'animations'] as const) {
    if (entry[key] !== undefined) {
      result[key] = entry[key]
    }
  }
  return result
}

function assetSource(pack: string, version: string | number, hash: string, entries: readonly AssetEntry[]): string {
  const ids = entries.map((entry) => entry.id).sort()
  const assets: Record<string, unknown> = {}
  for (const entry of [...entries].sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0))) {
    assets[entry.id] = metadata(entry)
  }
  return [
    '// Generated by lunego gen. Do not edit (LG014).',
    '',
    `export const AssetPack = ${JSON.stringify({ pack, version, hash })} as const`,
    `export type AssetPackId = typeof AssetPack.pack`,
    '',
    `export const AssetIds = ${JSON.stringify(
      Object.fromEntries(ids.map((id) => [id, id])),
      null,
      2,
    )} as const`,
    'export type AssetId = (typeof AssetIds)[keyof typeof AssetIds]',
    '',
    'export interface AssetAnimation {',
    '  readonly name: string',
    '  readonly columns: readonly number[]',
    '  readonly frames: number',
    '  readonly fps?: number | null',
    '}',
    '',
    'export interface AssetDisplay {',
    '  readonly file: string',
    '  readonly type: string',
    '  readonly frameWidth?: number',
    '  readonly frameHeight?: number',
    '  readonly columns?: number',
    '  readonly rows?: number',
    '  readonly frames?: number',
    '  readonly fps?: number | null',
    '  readonly anchor?: string',
    '  readonly animations?: readonly AssetAnimation[]',
    '}',
    '',
    `export const Assets = ${JSON.stringify(assets, null, 2)} as const satisfies Record<AssetId, AssetDisplay>`,
    '',
    'export function asset(id: AssetId): AssetDisplay {',
    '  return Assets[id]',
    '}',
    '',
  ].join('\n')
}

export async function generateAssets(cwd: string): Promise<AssetGeneration | null> {
  const manifestPath = join(cwd, 'assets', 'manifest.json')
  if (!(await pathExists(manifestPath))) {
    return null
  }
  const errors: string[] = []
  const text = await readFile(manifestPath, 'utf8')
  let manifest: AssetManifest
  try {
    manifest = JSON.parse(text) as AssetManifest
  } catch (error) {
    return {
      path: join(cwd, 'features', '_generated', 'assets.ts'),
      source: '',
      errors: [`LG009 assets/manifest.json is not valid JSON: ${error instanceof Error ? error.message : String(error)}`],
    }
  }
  if (typeof manifest.pack !== 'string' || manifest.pack.length === 0) {
    errors.push('LG009 assets/manifest.json requires a non-empty pack')
  }
  if (typeof manifest.version !== 'string' && typeof manifest.version !== 'number') {
    errors.push('LG009 assets/manifest.json requires a version')
  }
  if (!Array.isArray(manifest.assets)) {
    errors.push('LG009 assets/manifest.json requires an assets array')
    manifest = { ...manifest, assets: [] }
  }
  const seen = new Set<string>()
  for (let index = 0; index < manifest.assets.length; index += 1) {
    const entry = manifest.assets[index]
    validateEntry(entry, index, errors)
    if (typeof entry.id === 'string') {
      if (seen.has(entry.id)) {
        errors.push(`LG009 duplicate asset id ${entry.id}`)
      }
      seen.add(entry.id)
    }
    if (typeof entry.file === 'string') {
      const filePath = join(cwd, 'assets', entry.file)
      if (!(await pathExists(filePath))) {
        errors.push(`LG009 asset ${entry.id ?? index} file is missing: assets/${entry.file}`)
      }
    }
  }

  const hash = createHash('sha256')
  hash.update(JSON.stringify(manifest))
  for (const entry of [...manifest.assets].sort((left, right) => (left.id < right.id ? -1 : left.id > right.id ? 1 : 0))) {
    if (typeof entry.file !== 'string') {
      continue
    }
    const filePath = join(cwd, 'assets', entry.file)
    if (await pathExists(filePath)) {
      hash.update(toPosix(relative(cwd, filePath)))
      hash.update(await readFile(filePath))
    }
  }
  const path = join(cwd, 'features', '_generated', 'assets.ts')
  return {
    path,
    source: assetSource(manifest.pack ?? '', manifest.version ?? '', hash.digest('hex'), manifest.assets),
    errors,
  }
}
